const fs=require('fs'),vm=require('vm'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
const manifest=fs.readFileSync(path.join(root,'app/src/main/assets/manifest.webmanifest'),'utf8');
assert(html.includes('NUTRITRACK_5_2_PRIVACY_CONSENT'),'5.2 privacy marker missing');
assert(html.includes('This approval applies to one request only.'),'One-request consent explanation missing');
assert(html.includes('width:22px;height:22px'),'Consent touch target not enlarged');
assert(html.includes('Your API key stays in memory for this session only')===false,'Outdated API-key privacy description remains');
assert((html.match(/consumeAiConsent\(/g)||[]).length===4,'Three AI actions must consume consent through one helper');
assert(!html.includes('if(!$("aiConsent").checked)return toast("Consent is required before sending");'),'Old persistent consent guard remains');
const helper=html.match(/function consumeAiConsent\(message\)\{[\s\S]*?\n \}/);
assert(helper,'One-request consent helper missing');
let checked=true,events=0,toasts=[];
const sandbox={$:id=>id==='aiConsent'?{get checked(){return checked},set checked(v){checked=v},dispatchEvent:()=>events++}:null,toast:m=>toasts.push(m),Event:function(name){this.type=name}};
vm.createContext(sandbox);
vm.runInContext(helper[0]+';globalThis.consume=consumeAiConsent',sandbox);
assert.strictEqual(sandbox.consume('Need consent'),true);
assert.strictEqual(checked,false,'Consent must be consumed immediately');
assert.strictEqual(events,1,'Consent UI must be notified after reset');
assert.strictEqual(sandbox.consume('Need consent'),false,'A second request must require fresh consent');
assert.strictEqual(toasts.length,1);
assert(gradle.includes('versionCode 18')&&gradle.includes("versionName '6.0.0'"),'Android version must be 5.2.0/code 17');
assert(manifest.includes('NutriTrack 6.0'),'PWA version must be 5.2');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
assert(scripts.length,'Inline JavaScript missing');
for(const script of scripts)new vm.Script(script,{filename:'NutriTrack-5.2-inline.js'});
console.log('PASS: 5.2 inline JavaScript syntax');
console.log('PASS: consent consumed once for question, connection test and photo analysis');
console.log('PASS: consent checkbox has a larger, accessible touch target');
console.log('PASS: API-key storage description matches encrypted/session behavior');
console.log('PASS: Android and PWA 5.2 release metadata');
