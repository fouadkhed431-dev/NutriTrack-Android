const fs=require('fs');
const vm=require('vm');
const path=require('path');
const assert=require('assert');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const java=fs.readFileSync(path.join(root,'app/src/main/java/com/nutritrack/app/MainActivity.java'),'utf8');
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
assert(scripts.length>0,'Inline application script is missing');
const script=scripts.join('\n');
new vm.Script(script,{filename:'NutriTrack-inline.js'});
assert(script.includes('NUTRITRACK_COMPLETION_3'),'Completion JavaScript marker missing');
for(const id of ['aiProvider','aiSaveKey','aiClearKey','aiTest','aiMealPhoto','aiAnalyzeMeal','aiMealReview','approveMealEstimates','exportPdf','exportExcel','monthBars','monthFat','monthCarbs','weekMacros','mealSummaryToday','planAddSavedMeal','planAlternatives','favoriteToggle'])
  assert(html.includes('id="'+id+'"'),'Missing UI control: '+id);
for(const method of ['storeAiKey','readAiKey','deleteAiKey','exportPdfReport'])
  assert(java.includes(' '+method+'('),'Missing Android bridge method: '+method);
assert(java.includes('AndroidKeyStore'),'API keys must use Android Keystore');
assert(java.includes('AES/GCM/NoPadding'),'API keys must be encrypted at rest');
assert(java.includes('PdfDocument'),'Native PDF export is missing');
assert(!/sk-[A-Za-z0-9]{20,}/.test(html+java),'A hard-coded OpenAI key was found');
assert(!/AIza[0-9A-Za-z_-]{30,}/.test(html+java),'A hard-coded Gemini key was found');
assert(!script.includes('localStorage.setItem("openai"'),'API keys must not be stored in localStorage');
const sheetFn=script.match(/function sheetXml\(name,rows\)\{[^\n]*\}/);
const workbookFn=script.match(/function buildWorkbook\(\)\{[^\n]*\}/);
assert(sheetFn&&workbookFn,'Spreadsheet workbook builders are missing');
const sandbox={state:{entries:[{date:'2026-11-18',meal:'Lunch',name:'Rice & chicken',ar:'',grams:250,kcal:430,protein:32,fat:9,carbs:55,sugar:2}]},monthData:()=>[{key:'2026-11-18',kcal:430,protein:32,fat:9,carbs:55}],num:v=>Number(v)||0,escXml:v=>String(v==null?'':v).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;').replace(/'/g,'&apos;')};
vm.createContext(sandbox);
vm.runInContext(sheetFn[0]+'\n'+workbookFn[0]+'\nglobalThis.result=buildWorkbook()',sandbox);
assert(sandbox.result.includes('<Worksheet ss:Name="Food Diary">'));
assert(sandbox.result.includes('<Worksheet ss:Name="Last 30 Days">'));
assert(sandbox.result.includes('Rice &amp; chicken'));
const parseFn=script.match(/function parseMealItems\(raw\)\{[^\n]*\}/);
assert(parseFn,'Meal estimate parser is missing');
const parser={num:v=>Number(v)||0};vm.createContext(parser);
vm.runInContext(parseFn[0]+'\nglobalThis.parse=parseMealItems',parser);
const parsed=parser.parse('[{"name":"Grilled chicken","grams":150,"kcal":248,"protein":46,"fat":5,"carbs":0}]');
assert.strictEqual(parsed.length,1);
assert.strictEqual(parsed[0].grams,150);
assert.strictEqual(parsed[0].protein,46);
console.log('PASS: complete inline JavaScript syntax');
console.log('PASS: AI providers, consent, photo review and explicit approval UI');
console.log('PASS: Android Keystore encryption and native PDF bridge');
console.log('PASS: Excel workbook generation and XML escaping');
console.log('PASS: meal estimate JSON parsing');
console.log('PASS: dashboard, meal planner, alternatives and favorites controls');
